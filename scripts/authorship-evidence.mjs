// Dated authorship evidence for LikeLink's own work (code, texts, design).
//
// Writes legal/AUTHORSHIP_EVIDENCE.md: the repository history anchor (first
// and current commit with their dates), and SHA-256 fingerprints of the
// original works — source folders, the legal texts, the generated public
// pages. Committing the file (and pushing it to GitHub) gives every
// fingerprint a third-party timestamp. Run: node scripts/authorship-evidence.mjs
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const git = (...args) => execFileSync("git", args, { cwd: ROOT }).toString().trim();

// Works whose authorship we want to be able to prove, grouped for the report.
const WORKS = [
  ["Luna discovery engine and operating system", "src/lib/discovery"],
  ["Plans, billing and cancellation terms", "src/lib/plans.js", "src/lib/billing"],
  ["Legal texts (Hebrew)", "src/lib/legal"],
  ["Static public pages (pricing, legal)", "src/lib/staticPages", "public/pricing.html", "public/legal.html", "public/legal"],
  ["Studio interface", "src/components/studio", "src/components/sell"],
  ["Cloud services and API handlers", "src/lib/cloud", "api"],
];

function filesUnder(rel) {
  const abs = path.join(ROOT, rel);
  const st = statSync(abs, { throwIfNoEntry: false });
  if (!st) return [];
  if (st.isFile()) return [rel];
  return readdirSync(abs).sort().flatMap((n) => filesUnder(path.posix.join(rel.replace(/\\/g, "/"), n)));
}
// Line endings are normalised so a checkout on Windows fingerprints the same bytes as Git stores.
const sha = (buf) => createHash("sha256").update(buf).digest("hex");
const fileHash = (rel) => sha(readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n"));

const head = git("rev-parse", "HEAD");
const headDate = git("show", "-s", "--format=%cI", "HEAD");
const first = git("rev-list", "--max-parents=0", "HEAD").split("\n")[0];
const firstDate = git("show", "-s", "--format=%cI", first);
const commits = git("rev-list", "--count", "HEAD");
const remote = (() => { try { return git("remote", "get-url", "origin").replace(/\/\/[^@/]+@/, "//"); } catch { return "(none)"; } })();

const sections = WORKS.map(([title, ...paths]) => {
  const files = paths.flatMap(filesUnder).filter((f) => !/node_modules|\.bak$/.test(f));
  const rows = files.map((f) => [f, fileHash(f)]);
  const combined = sha(rows.map(([f, h]) => `${f}:${h}`).join("\n"));
  return { title, files: rows, combined };
});
const total = sha(sections.map((s) => s.combined).join("\n"));

const md = `# Authorship evidence — LikeLink

Generated by \`scripts/authorship-evidence.mjs\`. Each fingerprint is the SHA-256 of the file's text (LF line endings) at the commit below; the commit history and the push to GitHub date them.

| | |
|---|---|
| Repository | ${remote} |
| First commit | \`${first}\` — ${firstDate} |
| Fingerprinted commit (parent of the commit that adds this file) | \`${head}\` — ${headDate} |
| Commits in history | ${commits} |
| Combined fingerprint of all works below | \`${total}\` |

${sections.map((s) => `## ${s.title}

Combined: \`${s.combined}\` (${s.files.length} files)

<details><summary>Per-file fingerprints</summary>

| File | SHA-256 |
|---|---|
${s.files.map(([f, h]) => `| \`${f}\` | \`${h}\` |`).join("\n")}

</details>
`).join("\n")}`;

mkdirSync(path.join(ROOT, "legal"), { recursive: true });
writeFileSync(path.join(ROOT, "legal/AUTHORSHIP_EVIDENCE.md"), md, "utf8");
console.log(`wrote legal/AUTHORSHIP_EVIDENCE.md — ${sections.reduce((n, s) => n + s.files.length, 0)} files, combined ${total}`);
