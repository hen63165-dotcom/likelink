// Builds src/talkData.ts for the TalkSlides compositions from a finished "Talking slides" run
// (the presenter-preview pre-release: <spec>.tgz with voices.json, <id>.words.json and
// <id>.talk.mp4) and the spec in scripts/media/presenter/. The talking clips are copied to
// public/talk/, each cut just after its last word and sped up ×SPEED (voice and lips together,
// so they stay in sync; the pitch is kept) so a reel of eight slides stays near 40 s.
// A line whose clip is missing stops the build (never a silent gap).
//   node talk-data.mjs <unpacked run dir> [spec file name]
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const specName = process.argv[3] || "talk-slides-20261115.json";
const spec = JSON.parse(readFileSync(join("..", "..", "scripts", "media", "presenter", specName), "utf8"));
const voices = JSON.parse(readFileSync(join(dir, "voices.json"), "utf8"));
const seconds = Object.fromEntries(voices.lines.map((l) => [l.id, l.seconds]));
const SPEED = 1.17;
const TAIL = 0.22; // after the last word
const reels = { mistakes: [], "radar-creators": [] };
for (const l of spec.lines) {
  const clip = join(dir, `${l.id}.talk.mp4`);
  if (!existsSync(clip)) throw new Error(`${l.id}: no talking clip`);
  const raw = JSON.parse(readFileSync(join(dir, `${l.id}.words.json`), "utf8"));
  const end = Math.min(seconds[l.id], Math.max(...raw.map((w) => w[0] + w[1])) + TAIL);
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", clip, "-filter_complex",
    `[0:v]trim=0:${end},setpts=(PTS-STARTPTS)/${SPEED}[v];[0:a]atrim=0:${end},asetpts=PTS-STARTPTS,atempo=${SPEED}[a]`,
    "-map", "[v]", "-map", "[a]", "-r", "25", "-c:v", "libx264", "-crf", "16", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k",
    join("public", "talk", `${l.id}.talk.mp4`)]);
  // the spoken words with the line's own punctuation back on them (the bubble breaks after it)
  const tokens = l.say.split(/\s+/);
  const bare = (x) => x.replace(/[^\p{L}\p{N}]/gu, "");
  let k = 0;
  const words = raw.map(([a, b, w]) => {
    const j = tokens.findIndex((t, i) => i >= k && bare(t) === bare(w));
    if (j >= 0) k = j + 1;
    return [+(a / SPEED).toFixed(3), +(b / SPEED).toFixed(3), j >= 0 ? tokens[j] : w];
  });
  reels[l.reel].push({
    id: l.id,
    presenter: l.presenter,
    slide: `talk/${l.reel}-${String(l.slide).padStart(2, "0")}.png`,
    dark: l.slide === 8,
    seconds: +(end / SPEED).toFixed(3),
    words,
    video: `talk/${l.id}.talk.mp4`,
  });
}
const header = "🎙️ שירה ונועה מסבירות";
const out = `// Generated by talk-data.mjs from the "Talking slides" run (${specName}); do not edit by hand.
import type { TalkProps } from "./TalkSlides";

export const TALK_MISTAKES: TalkProps = ${JSON.stringify({ lines: reels.mistakes, bed: "talk/bed.m4a", header }, null, 1)};
export const TALK_RADAR: TalkProps = ${JSON.stringify({ lines: reels["radar-creators"], bed: "talk/bed.m4a", header }, null, 1)};
`;
writeFileSync(join("src", "talkData.ts"), out);
