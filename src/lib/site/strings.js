export function siteT(lang) {
  const dict = SITE_STRINGS[lang] || SITE_STRINGS.he;
  return (key, vars) => {
    let out = dict[key] ?? SITE_STRINGS.he[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
}
